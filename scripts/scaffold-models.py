#!/usr/bin/env python
"""scaffold-models.py — information_schema 反推生成 Django models（DB-First，家族 §6.2 口径）。

真源=库（本仓禁 migrate/seed；schema SSOT = lab-management-system-shared/src/db/
schema.ts）。与 go/scripts/scaffold-models.mjs（REQ-2026-004）、springboot
scaffold-entities / laravel scaffold-models 同构第六链。产物 src/entities/models.py
禁手改；schema 漂移由 tests/test_schema_parity.py 逐列对账拦截。

用法：
  DATABASE_URL=postgresql://... python scripts/scaffold-models.py           # 生成
  DATABASE_URL=... python scripts/scaffold-models.py --check                # 复跑比对，漂移 exit 1

fail-fast：DATABASE_URL 未设 / 未知 PG 类型 / 未知默认值形状 / 列名非法标识符——一律
raise，不静默兜底（suite-hard-rules §1）。确定性输出：表名字典序、列按 ordinal_position、
无时间戳——双跑字节幂等。
"""

from __future__ import annotations

import keyword
import re
import sys
from pathlib import Path

import psycopg2

ROOT = Path(__file__).resolve().parent.parent
OUT_FILE = ROOT / "src" / "entities" / "models.py"

# 家族 bookkeeping 表不进生成区（与 go generator 同集）
EXCLUDE_TABLES = {
    "__drizzle_migrations",
    "schema_migrations",
    "ar_internal_metadata",
}

# PG udt_name → Django 字段类。未知类型 raise 不静默（家族口径：生成器不猜）。
FIELD_BY_UDT = {
    "text": "TextField",
    "varchar": "TextField",
    "int4": "IntegerField",
    "int8": "BigIntegerField",
    "bool": "BooleanField",
    "jsonb": "JSONField",
    "date": "DateField",
    "timestamp": "DateTimeField",
    "timestamptz": "DateTimeField",
}


def pascal_case(table: str) -> str:
    return "".join(part.capitalize() for part in table.split("_"))


def parse_default(raw: str, udt: str) -> str:
    """PG column_default 字面量 → Django db_default 实参（可执行表达式文本）。

    家族库形状（2026-11-02 全量盘点）：''::text 文本、整数字面量、true/false、
    '{}'::jsonb / '[]'::jsonb。函数型默认（now() 等）家族无此形状——raise fail-loud。
    """
    m = re.match(r"^'((?:[^']|'')*)'::", raw)
    if m:
        literal = m.group(1).replace("''", "'")
        if udt == "jsonb":
            if literal == "{}":
                return "dict"  # callable 形：INSERT 由 Django 侧带 '{}'::jsonb（已实测）
            if literal == "[]":
                return "list"
            raise SystemExit(f"jsonb 非集合字面量默认 {raw!r}：不在家族形状内，raise 不静默")
        return repr(literal)
    if raw in ("true", "false"):
        return raw.capitalize()
    if re.match(r"^-?\d+$", raw):
        return raw
    raise SystemExit(f"未知默认值形状 {raw!r}（函数型/序列型不在家族形状内），raise 不静默")


def fetch_tables(cur) -> list[str]:  # type: ignore[no-untyped-def]
    cur.execute("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    return sorted(row[0] for row in cur.fetchall() if row[0] not in EXCLUDE_TABLES)


def fetch_columns(cur, table: str) -> list[dict]:  # type: ignore[no-untyped-def]
    cur.execute(
        """
        SELECT c.column_name, c.udt_name, c.is_nullable = 'YES', c.column_default,
               EXISTS (
                 SELECT 1 FROM information_schema.table_constraints tc
                 JOIN information_schema.key_column_usage k
                   ON tc.constraint_name = k.constraint_name
                  AND tc.table_schema = k.table_schema
                  AND tc.table_name = k.table_name
                 WHERE tc.constraint_type = 'PRIMARY KEY'
                   AND tc.table_schema = c.table_schema
                   AND tc.table_name = c.table_name
                   AND k.column_name = c.column_name
               )
        FROM information_schema.columns c
        WHERE c.table_schema = 'public' AND c.table_name = %s
        ORDER BY c.ordinal_position
        """,
        [table],
    )
    cols = []
    for name, udt, nullable, default, is_pk in cur.fetchall():
        if not name.isidentifier() or keyword.iskeyword(name):
            raise SystemExit(f"{table}.{name}：非合法 Python 标识符，raise 不静默")
        if udt not in FIELD_BY_UDT:
            raise SystemExit(f"{table}.{name}：未知 PG 类型 {udt}，raise 不静默")
        cols.append(
            {
                "name": name,
                "field": FIELD_BY_UDT[udt],
                "nullable": nullable,
                "default": parse_default(default, udt) if default is not None else None,
                "is_pk": is_pk,
            }
        )
    if not any(c["is_pk"] for c in cols):
        raise SystemExit(f"{table}：无主键，Django ORM 必须有 pk，raise 不静默")
    return cols


def render_column(col: dict) -> str:  # type: ignore[no-untyped-def]
    args = [f'db_column="{col["name"]}"']
    if col["is_pk"]:
        args.append("primary_key=True")
    if col["nullable"]:
        args.append("null=True")
    if col["default"] is not None:
        args.append(f"db_default={col['default']}")
    return f"    {col['name']} = models.{col['field']}({', '.join(args)})"


HEADER = """\
# Code generated by scripts/scaffold-models.py. DO NOT EDIT.
# DB-First scaffold：由 information_schema 反推生成（家族 §6.2 口径；schema SSOT =
# lab-management-system-shared/src/db/schema.ts，本仓禁 migrate/seed）。禁手改——
# schema 漂移由 tests/test_schema_parity.py 逐列对账拦截；复跑比对
# `DATABASE_URL=... python scripts/scaffold-models.py --check`。
# 手写业务方法写在各域 app，不进本文件。字段含义见 shared 仓 schema.ts。

from django.db import models
"""


def generate() -> str:
    dsn = __import__("os").environ.get("DATABASE_URL")
    if not dsn:
        raise SystemExit("DATABASE_URL 未设（fail-fast，禁默认值兜底——suite-hard-rules §1）")
    with psycopg2.connect(dsn) as conn, conn.cursor() as cur:
        chunks = [HEADER]
        for table in fetch_tables(cur):
            cols = fetch_columns(cur, table)
            body = "\n".join(render_column(c) for c in cols)
            chunks.append(
                f"\n\nclass {pascal_case(table)}(models.Model):\n{body}\n\n"
                f"    class Meta:\n        managed = False\n        db_table = {table!r}\n"
            )
        chunks.append("\n")
        return "".join(chunks)


def main() -> None:
    content = generate()
    if "--check" in sys.argv[1:]:
        existing = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.is_file() else None
        if existing == content:
            print(f"codegen.idempotent PASS：{OUT_FILE.relative_to(ROOT)} 与库一致")
            return
        raise SystemExit(
            f"codegen 漂移：{OUT_FILE.relative_to(ROOT)} 与库 information_schema 不一致"
            "——重跑生成器（不带 --check）或按 §6.2 收链"
        )
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(content, encoding="utf-8", newline="\n")
    print(f"generated {OUT_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
